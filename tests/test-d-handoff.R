source('tests/helper.R');source_test_runtime();source('R/public_privacy.R')
work<-file.path(getwd(),'.artifact-temp','d-handoff');dir.create(work,recursive=TRUE,showWarnings=FALSE)
registry_data<-data.frame(patientid=1:21,event_date=c(rep(c('2024-01-01','2025-01-01'),each=10),'unknown'),Region=c(rep(c('Capital','Zealand'),each=10),'PRIVATE UNKNOWN'))
vital_data<-data.frame(subject=1:21,displayname=c(rep(c('Puls','SpO2'),each=10),'PRIVATE UNKNOWN'),meas_value=as.character(1:21),recorded_time=rep('2025-01-01T12:00:00Z',21))
write.csv(registry_data,file.path(work,'registry.csv'),row.names=FALSE)
write.csv(vital_data,file.path(work,'vital.csv'),row.names=FALSE)
mapping<-file.path(work,'keys.csv');write.csv(data.frame(table_name=c('RKKP_CLL','SP_VitaleVaerdier'),person_key=c('patientid','subject'),reviewed=TRUE),mapping,row.names=FALSE)
Sys.setenv(DALYCARE_REGISTRY_PERSON_KEYS_FILE=mapping)
map<-data.frame(table_name=c('RKKP_CLL','SP_VitaleVaerdier'),source_type='file',source=c(file.path(work,'registry.csv'),file.path(work,'vital.csv')),priority=1:2,profile_mode='full',domain=c('RKKP','SP'),subdomain=c('CLL','Vitals'),atlas_role=c('clinical_registry','vitals'))
mapfile<-file.path(work,'sources.tsv');write.table(map,mapfile,sep='\t',quote=FALSE,row.names=FALSE)
r<-run_atlas(getwd(),mapfile,file.path(work,'runs'),'report')
registry<-atlas_output_registry('.')
context<-atlas_read_build_context(r$run_dir,registry)
expect_true(all(c('coverage_evidence','vital_descriptors','vital_descriptor_assessment')%in%unlist(context$bindings)))
read_panel<-function(id){spec<-Filter(function(s)s$id==id,registry$artifacts)[[1]];atlas_read_registered_csv(file.path(r$run_dir,spec$source_file),spec)}
expect_true(any(read_panel('coverage_evidence')$release_status=='withheld_privacy'))
expect_equal(sort(read_panel('vital_descriptors')$descriptor),c('Puls','SpO2'))
expect_true(all(read_panel('vital_descriptor_assessment')$inventory_status=='partial_withheld'))
rebuilt<-atlas_payload_from_run_outputs(r$run_dir,'.')
expect_false(any(c('coverage_evidence','vital_descriptors','vital_descriptor_assessment')%in%names(rebuilt$payload$panels)))
years<-rebuilt$payload$panels$atlas_temporal_coverage_years
expect_true(any(vapply(years,function(x)identical(as.character(x$year),'2024'),logical(1))))
expect_true(all(vapply(Filter(function(x)identical(x$table_name,'RKKP_CLL'),years),function(x)is.null(x$n_rows)&&identical(x$count_privacy_status,'withheld_partition_counts'),logical(1))))
expect_true(any(vapply(rebuilt$payload$semantic_dictionary,function(x)identical(x$raw_descriptor,'Puls'),logical(1))))
evidence<-atlas_output_evidence(r$run_dir,'.')
expect_true(all(vapply(Filter(function(x)x$id%in%c('coverage_evidence','vital_descriptors','vital_descriptor_assessment'),evidence),function(x)!length(x$rows),logical(1))))
# Registered profile read retains sample metadata; public copy omits it, including N=1.
spec<-Filter(function(s)s$id=='column_profiles',registry$artifacts)[[1]]
profile<-read.csv(file.path(r$run_dir,spec$source_file),check.names=FALSE)
profile$sample_size<-1;profile$eligible_n<-1;profile$sampling_method<-'algorithm_r_reservoir';profile$sampling_complete<-TRUE
write_csv(profile,file.path(work,'profiles.csv'))
loaded<-atlas_read_registered_csv(file.path(work,'profiles.csv'),spec)
expect_true(all(loaded$sample_size==1))
guard<-atlas_public_privacy(list(column_profile_rows=atlas_evidence_rows(loaded)),'.')
expect_true(all(vapply(guard$column_profile_rows,function(x)is.null(x$sample_size)&&is.null(x$eligible_n),logical(1))))
Sys.unsetenv('DALYCARE_REGISTRY_PERSON_KEYS_FILE')
cat('PASS D actual runner, registered internal CSVs, offline rebuild, controlled descriptors and sampling public boundary\n')
