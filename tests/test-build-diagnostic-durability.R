source('tests/helper.R');source_test_runtime()
local({
  tmp <- tempfile('diagnostic-durability-');dir.create(tmp)
  on.exit(unlink(tmp,recursive=TRUE),add=TRUE)
  path <- file.path(tmp,'status.tsv');writeLines('previous valid status',path)
  failure <- try(atlas_lifecycle_atomic_write(path,function(stage) {
    writeLines('interrupted partial status',stage)
    stop('synthetic disk failure')
  }),silent=TRUE)
  expect_true(inherits(failure,'try-error'))
  expect_equal(readLines(path),'previous valid status')
  atlas_lifecycle_atomic_write(path,function(stage)writeLines('new valid status',stage))
  expect_equal(readLines(path),'new valid status')
  state <- atlas_lifecycle_start(tmp,file.path(tmp,'runs'))
  log <- file.path(state$log_dirs[1],'atlas_execution_log.tsv')
  prefix <- readLines(log)
  atlas_lifecycle_stage(state,'collection')
  expect_equal(head(readLines(log),length(prefix)),prefix)
  # A pre-existing log must be appended to, preserving already flushed evidence.
  write('retained internal diagnostic',log,append=TRUE)
  atlas_lifecycle_event(state,'info','Source collection progress')
  expect_true(any(grepl('retained internal diagnostic',readLines(log),fixed=TRUE)))
  expect_true(any(grepl('Source collection progress',readLines(log),fixed=TRUE)))
})
cat('Atomic status replacement and append-only flushed execution log passed\n')
