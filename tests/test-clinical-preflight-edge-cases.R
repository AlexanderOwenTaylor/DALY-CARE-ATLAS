source('tests/helper.R');source_test_runtime('.')
Sys.unsetenv('DALYCARE_REGISTRY_PERSON_KEYS_FILE')
local({
  originals<-mget(c('dbi_connection_for','registry_summary_db_dialect','dbi_table_ref','atlas_clinical_probe_query'),envir=.GlobalEnv)
  on.exit(list2env(originals,envir=.GlobalEnv))
  assign('dbi_connection_for',function(...)DBI::ANSI(),envir=.GlobalEnv)
  assign('registry_summary_db_dialect',function(...)'postgres',envir=.GlobalEnv)
  assign('dbi_table_ref',function(...)'synthetic_registry',envir=.GlobalEnv)
  assign('atlas_clinical_probe_query',function(conn,sql,...)list(status='ok',groups=if(startsWith(sql,'WITH raw'))data.frame(encoding=character(),n_people=numeric()) else data.frame(missing=FALSE)),envir=.GlobalEnv)
  schema<-data.frame(column_name=c('patientid','Beh_Immunterapi'),data_type=c('integer','text'))
  adapter<-list(table_schema=function(...)schema,connections=list())
  sources<-data.frame(table_name='RKKP_CLL')
  resolution<-data.frame(source_index=1,resolution_status='resolved',db_name='synthetic',schema='public',table='RKKP_CLL')
  failures<-character()
  check<-function(name,expr)tryCatch(force(expr),error=function(e){failures<<-c(failures,paste(name,conditionMessage(e)));cat('REGRESSION:',tail(failures,1),'\n')})
  check('empty registry preflight',{
    destination<-tempfile('empty-registry-preflight-')
    result<-atlas_clinical_preflight(sources,adapter,'.',destination,probe=TRUE,resolution=resolution)
    expect_true(file.exists(result$readiness_file))
    expect_true(nrow(result$encoding_diagnostics)==1)
    expect_equal(result$encoding_diagnostics$encoding,'empty_source')
    expect_equal(result$encoding_diagnostics$n_people,0)
    expect_equal(result$encoding_diagnostics$status,'ok')
  })
  check('reviewed missing key preservation',{
    mapping<-tempfile(fileext='.csv')
    write.csv(data.frame(table_name='RKKP_CLL',person_key='REVIEWED_LINK',reviewed=TRUE),mapping,row.names=FALSE)
    Sys.setenv(DALYCARE_REGISTRY_PERSON_KEYS_FILE=mapping)
    on.exit(Sys.unsetenv('DALYCARE_REGISTRY_PERSON_KEYS_FILE'),add=TRUE)
    for(unavailable in c(FALSE,TRUE)) {
      destination<-tempfile('missing-configured-key-')
      adapter$table_schema<-if(unavailable)function(...)stop('unavailable') else function(...)schema
      result<-atlas_clinical_preflight(sources,adapter,'.',destination,resolution=resolution)
      draft<-read.csv(file.path(destination,'logs','person-keys.review-required.csv'))
      expect_equal(draft$person_key,'REVIEWED_LINK');expect_true(draft$reviewed)
      row<-result$readiness[result$readiness$requirement=='person_key',]
      expect_equal(row$source_column,'REVIEWED_LINK')
      expect_equal(row$status,if(unavailable)'schema_unavailable' else 'column_absent')
      expect_equal(registry_summary_person_key('RKKP_CLL',schema$column_name)$status,'missing_person_key')
    }
  })
  if(length(failures))stop(paste(failures,collapse='\n'),call.=FALSE)
})
cat('PASS empty registry preflight and preservation of reviewed keys across missing schemas\n')
