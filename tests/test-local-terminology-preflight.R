source('tests/helper.R');source_test_runtime()
local({
  root <- normalizePath('.',winslash='/')
  tmp <- tempfile('terminology-preflight-');dir.create(tmp)
  on.exit(unlink(tmp,recursive=TRUE),add=TRUE)
  project <- file.path(tmp,'project');dir.create(project)
  file.copy(file.path(root,'config'),project,recursive=TRUE)
  file.copy(file.path(root,'inst'),project,recursive=TRUE)
  dictionary <- file.path(project,'config/npu-display-dictionary.csv')
  connection <- file(dictionary,'r+b');writeBin(charToRaw('X'),connection);close(connection)
  calls <- 0L; original <- resolve_dalycare_sources
  on.exit(assign('resolve_dalycare_sources',original,envir=.GlobalEnv),add=TRUE)
  assign('resolve_dalycare_sources',function(...) {calls <<- calls+1L;stop('Unexpected collection')},envir=.GlobalEnv)
  failure <- tryCatch(run_atlas(project,file.path(root,'config/source-map.example.tsv'),file.path(tmp,'runs')),error=identity)
  expect_equal(calls,0L,'Corrupt terminology must stop before source collection.')
  expect_true(inherits(failure,'atlas_build_error'))
  expect_equal(failure$stage,'preflight')
  expect_equal(failure$code,'invalid_dictionary')
  expect_equal(failure$resource,'pinned local terminology')
  cat('Corrupt local terminology blocked before collection.\n')
})
