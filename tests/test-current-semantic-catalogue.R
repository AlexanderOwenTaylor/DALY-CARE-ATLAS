source('tests/helper.R')
source_test_runtime()
sources <- data.frame(table_name=c('RKKP_DaMyDa','S.Ø'),schema=c('public','special'),table=c('damyda','Ø'))
columns <- data.frame(table_name=c('RKKP_DaMyDa','S.Ø','S.Ø','S.Ø'),column_name=c('Reg_Haemoglobin','patientid','Mystery.Ø','Mystery-Ø'),profile_kind=c('numeric','sensitive','suppressed','metadata_only'),is_sensitive=c(FALSE,TRUE,FALSE,FALSE),n_rows=NA_real_)
old <- Sys.getenv('DALYCARE_CARTOGRAPHY_PATH',unset='')
historical <- tempfile();dir.create(historical)
writeLines('source_name\tcolumn\tn_rows\nHISTORIC\tghost\t999999',file.path(historical,'cartography_registry.tsv'))
Sys.setenv(DALYCARE_CARTOGRAPHY_PATH=historical)
x <- build_semantic_outputs(getwd(),sources,columns)
Sys.setenv(DALYCARE_CARTOGRAPHY_PATH=old)
d <- x$dictionary
expect_equal(nrow(d),4L,'Every exact current pair, including identifiers, unknown and withheld columns, must survive.')
expect_equal(length(unique(d$semantic_id)),4L,'Punctuation and Unicode identities must not collide.')
expect_true(all(is.na(d$n_rows)) && all(is.na(d$n_patients)),'Metadata labels cannot import historical counts.')
expect_true(any(d$clinical_variable=='Haemoglobin'),'Reviewed source-field labels should resolve.')
expect_true(all(d$semantic_meaning[d$raw_column %in% c('Mystery.Ø','Mystery-Ø')]=='Description unavailable'),'Unknown descriptions remain explicit.')
expect_true(all(is.na(d$unit) | d$unit==''),'Names and suffixes never verify stored units.')
expect_true(any(grepl('Mystery.Ø',d$search_terms,fixed=TRUE)),'Search must retain exact Unicode identifiers.')
many <- data.frame(table_name='S.Ø',column_name=paste0('field.',seq_len(5101)))
full <- build_semantic_outputs(getwd(),sources,many)
expect_equal(nrow(full$dictionary),5101L,'All columns must survive beyond former display ceilings.')
expect_equal(nrow(full$panel_links),5101L,'Every column needs a stable detail route.')
panels <- list(vital_descriptors=data.frame(source_name='S.Ø',name_col='meas.name',value_col='result',descriptor=c('Vægt',"Unknown 'descriptor'"),unit='POISON_UNIT'))
v <- build_semantic_outputs(getwd(),sources,columns,panels)$dictionary
v <- v[v$data_shape=='long_descriptor_table',,drop=FALSE]
expect_equal(nrow(v),2L,'Every current descriptor needs its own row.')
expect_true(all(v$raw_column=='meas.name' & v$value_column=='result'),'Descriptor and result field names must remain together.')
expect_true(any(v$evidence_filter=="\"meas.name\" = 'Unknown ''descriptor'''"),'Filters must escape exact identifiers and descriptor literals.')
expect_true(all(is.na(v$unit) | v$unit==''),'Descriptor reference/poisoned units cannot verify stored units.')
expect_true(validate_local_terminology(getwd()),'Pinned local release must validate offline.')
release <- read.csv('config/npu-display-dictionary.csv',stringsAsFactors=FALSE,fileEncoding='UTF-8')
expect_equal(sum(release$status=='active'),25699L,'Official active-current names are separate from consensus grouping and legacy definitions.')
expect_equal(length(unique(release$code)),nrow(release))
expect_true(any(release$code=='NPU17597' & release$status=='reviewed_legacy_reference'),'Prior reviewed definition remains discoverable with explicit legacy provenance.')
codes <- build_semantic_outputs(getwd(),sources,columns,list(lab_npu_code_coverage=data.frame(table_name='RKKP_DaMyDa',code_column='analysis.code',lab_code=c('NPU04998','NPU99999'),n=c(999999,99))))
expect_equal(nrow(codes$code_map),2L,'Current observed code identities receive local terminology definitions, including unknown codes.')
expect_true(any(codes$code_map$code=='NPU04998' & codes$code_map$code_name=='Creatinine'),'Exact NPU names resolve offline.')
expect_true(any(codes$code_map$code=='NPU99999' & codes$code_map$code_name=='Description unavailable'),'Unknown code meaning stays explicit.')
expect_true(all(is.na(codes$code_map$n_rows)) && all(is.na(codes$code_map$n_patients)),'Terminology lookup cannot introduce observed counts.')
bad <- tempfile();dir.create(bad);dir.create(file.path(bad,'config'))
expect_true(inherits(tryCatch(validate_local_terminology(bad),error=identity),'error'),'Missing terminology must fail closed.')
args <- list(sources=sources,column_profiles=columns,panels=list(),semantic_dictionary=empty_semantic_data_dictionary())
rebuilt <- semantic_rehydrate_args(args,getwd())
expect_equal(nrow(rebuilt$semantic_dictionary),4L,'Empty semantic exports rebuild without database access.')
expect_true(nrow(rebuilt$clinical_concepts)>0,'Rehydration also restores concept routes.')
args$semantic_dictionary <- x$dictionary
args$semantic_dictionary$semantic_meaning[[1]] <- 'Explicit current run interpretation'
expect_equal(semantic_rehydrate_args(args,getwd())$semantic_dictionary$semantic_meaning[[1]],'Explicit current run interpretation','Valid populated run semantics are preserved.')
file.copy('config/terminology',file.path(bad,'config'),recursive=TRUE)
file.copy('config/npu-display-dictionary.csv',file.path(bad,'config'))
con <- file(file.path(bad,'config/npu-display-dictionary.csv'),'r+b');writeBin(charToRaw('X'),con);close(con)
expect_true(inherits(tryCatch(validate_local_terminology(bad),error=identity),'error'),'Corrupt same-size local terminology must fail checksums.')
cat('Current semantic catalogue checks passed.\n')
