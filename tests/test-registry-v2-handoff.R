source('tests/helper.R');source_test_runtime('.')
source('R/public_privacy.R');source('tests/registry-v2-fixture.R');work<-registry_v2_test_setup()
source('R/site_bundle.R')
data<-data.frame(patientid=1:20,Reg_Haemoglobin=rep(c('1','11','21','31'),each=5))
rows<-registry_field_summaries(data,'RKKP_DaMyDa','.')
rows<-registry_v2_complete(rows,'.')
expect_equal(nrow(rows),217L)
spec<-Filter(function(s)s$id=='registry_field_summaries',atlas_output_registry('.')$artifacts)[[1]]
path<-file.path(work,'handoff.csv');write.csv(rows,path,row.names=FALSE,na='')
read<-atlas_read_registered_csv(path,spec)
expect_equal(atlas_registry_summary_guard(read,'.'),atlas_registry_summary_guard(rows,'.'))
payload<-list(run_id='synthetic-v2',panels=list(registry_field_summaries=atlas_evidence_rows(rows)))
tables<-atlas_output_evidence(NULL,'.',payload)
table<-Filter(function(t)t$id=='registry_field_summaries',tables)[[1]]
expect_true(isTRUE(all.equal(table$rows,payload$panels$registry_field_summaries)))
expect_true(all(vapply(table$rows,function(r)identical(names(r),registry_v2_schema),logical(1))))
run<-file.path(work,'bundle');dir.create(run,recursive=TRUE,showWarnings=FALSE)
invisible(write_static_atlas(run,payload,'.',tables))
expect_file(file.path(run,'site/registry-v2.js'))
resource<-paste(readLines(file.path(run,'site/registry-v2.js'),warn=FALSE),collapse='\n')
expect_false(grepl('evidence_source|evidence_revision|synthetic fixture|unit.json|policy.json',resource))
cat('PASS v2 all-217 outcomes, typed CSV/evidence handoff and offline/hosting site resource\n')
