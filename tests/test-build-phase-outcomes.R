source('tests/helper.R');source_test_runtime()
local({
  root <- normalizePath('.',winslash='/')
  sources <- data.frame(table_name='fixture',load_status='ok',profile_mode='full')
  report <- atlas_completion_report(sources,sources,NULL,root,'fixture','complete')
  values <- setNames(report$summary$value,report$summary$metric)
  expect_equal(values[['collection_status']],'complete')
  expect_equal(values[['interpretation_status']],'complete')
  expect_equal(values[['website_status']],'complete')
  expect_equal(values[['packaging_status']],'not_implemented')
  expect_equal(values[['overall_status']],'partial')
  sources$load_status <- 'failed'
  report <- atlas_completion_report(sources,sources,NULL,root,'fixture','complete')
  values <- setNames(report$summary$value,report$summary$metric)
  expect_equal(values[['collection_status']],'partial')
  expect_equal(values[['overall_status']],'partial')
  sources$load_status <- 'ok';sources$profile_mode <- 'schema'
  values <- setNames(atlas_completion_report(sources,sources,NULL,root,'fixture','complete')$summary$value,
    atlas_completion_report(sources,sources,NULL,root,'fixture','complete')$summary$metric)
  expect_equal(values[['collection_status']],'partial')
  partial_dir <- tempfile('partial-failure-');dir.create(partial_dir)
  on.exit(unlink(partial_dir,recursive=TRUE),add=TRUE)
  map <- read.delim('config/source-map.example.tsv',stringsAsFactors=FALSE)[1,,drop=FALSE]
  map$source <- file.path(partial_dir,'missing.csv')
  map_path <- file.path(partial_dir,'source-map.tsv');write.table(map,map_path,sep='\t',quote=FALSE,row.names=FALSE)
  original_coverage <- build_coverage_panels
  assign('build_coverage_panels',function(...)stop('private interpretation failure'),envir=.GlobalEnv)
  on.exit(assign('build_coverage_panels',original_coverage,envir=.GlobalEnv),add=TRUE)
  failure <- tryCatch(run_atlas(root,map_path,file.path(partial_dir,'runs')),error=identity)
  assign('build_coverage_panels',original_coverage,envir=.GlobalEnv)
  state <- read.delim(failure$diagnostics,stringsAsFactors=FALSE)
  expect_equal(state$value[state$metric=='failing_stage'],'interpretation')
  expect_equal(state$value[state$metric=='collection_status'],'partial','Failed source collection must remain partial when interpretation fails.')
  expect_file(file.path(failure$run_dir,'outputs/atlas_completion_summary.csv'))
  tmp <- tempfile('startup-recovery-');dir.create(file.path(tmp,'scripts'),recursive=TRUE)
  on.exit({setwd(root);unlink(tmp,recursive=TRUE)},add=TRUE)
  file.copy('RUN_DALYCARE_ATLAS_73_SOURCE.R',tmp)
  dir.create(file.path(tmp,'R'));file.copy('R/run_atlas.R',file.path(tmp,'R'))
  writeLines('stop("password=hunter2 SELECT patientid FROM person WHERE id=1234567890")',file.path(tmp,'scripts/run_atlas.R'))
  text <- capture.output(source(file.path(tmp,'RUN_DALYCARE_ATLAS_73_SOURCE.R'),local=new.env(parent=.GlobalEnv)))
  setwd(root)
  expect_true(dalycare_atlas_failed)
  expect_true(inherits(dalycare_atlas_last_error,'atlas_build_error'))
  expect_file(dalycare_atlas_last_error$diagnostics)
  state <- read.delim(dalycare_atlas_last_error$diagnostics,stringsAsFactors=FALSE)
  expect_equal(state$value[state$metric=='failing_stage'],'startup')
  expect_false(any(grepl('hunter2|SELECT|patientid|1234567890',c(text,state$value))))
})
cat('Separate build phases and source startup recovery passed\n')
