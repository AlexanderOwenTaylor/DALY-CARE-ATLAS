# Actual rehydration + clinical payload entry preserves every proven schema pair.
source_name<-'SYNTHETIC_LOGICAL_Ø'
fields<-c('patientid','cpr','socialsecurity','måling "højde"','resultat-værdi',paste0('field_',seq_len(2195)))
sources<-data.frame(table_name=source_name,table='PHYSICAL_ALIAS',schema='public',load_status='ok',n_rows=0,n_cols=2200,domain='SP',subdomain='Synthetic',atlas_role='source',source_type='file',source='synthetic.csv',profile_mode='metadata')
columns<-data.frame(table_name=source_name,column_name=fields,column_type='character')
profiles<-basic_column_profiles(columns)
semantic<-build_semantic_outputs('.',sources,profiles,list(vital_descriptors=data.frame(source_name=source_name,name_col='måling "højde"',value_col='resultat-værdi',descriptor='Højde')))
args<-semantic_rehydrate_args(list(sources=sources,column_profiles=profiles,panels=list(),semantic_dictionary=semantic$dictionary),'.')
checks<-data.frame(table_name=character(),check_id=character(),severity=character(),message=character())
payload<-atlas_payload('synthetic-metadata','2026-01-01',sources,columns,checks,list(),column_profiles=profiles,semantic_dictionary=args$semantic_dictionary,panel_raw_fields=args$panel_raw_fields)
safe<-atlas_public_privacy(payload,'.')
generic<-Filter(function(row)is.null(row$raw_descriptor)||!nzchar(row$raw_descriptor),safe$semantic_dictionary_rows)
actual<-vapply(generic,function(row)row$raw_column,character(1))
long<-Filter(function(row)identical(row$raw_descriptor,'Højde'),safe$semantic_dictionary_rows)
expect_equal(length(long),1L,'Independently reviewed saved descriptor survives the actual HTML/guard path.')
expect_equal(long[[1]]$mapping_status,'saved_definition_inventory_unassessed')
expect_equal(sort(actual),sort(fields),'All 2200 exact schema field names survive hydration and HTML sanitization.')
expect_true(all(vapply(safe$semantic_dictionary_rows,function(row)identical(row$source_name,source_name),logical(1))))
expect_true(all(vapply(generic,function(row)identical(row$table_name,'PHYSICAL_ALIAS'),logical(1))))
expect_false(any(grepl('[sensitive]',actual,fixed=TRUE)))
expect_equal(sort(vapply(safe$column_profile_rows,function(row)row$column_name,character(1))),sort(fields))
atlas_evidence_audit(safe,'.')
expect_true(any(vapply(safe$review_clinical_variables$raw_fields,function(row)identical(row$raw_descriptor,'Højde'),logical(1))))
jsonlite::write_json(safe,'.artifact-temp/registry-v2/metadata-entry.json',auto_unbox=TRUE,null='null',digits=NA)
cat('PASS real semantic rehydration + atlas_payload entry preserves 2200 exact fields, sensitive schema identifiers, Unicode and physical/logical aliases\n')
