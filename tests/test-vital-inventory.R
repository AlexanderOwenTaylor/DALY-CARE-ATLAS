source('tests/helper.R');source_test_runtime()
Sys.unsetenv('DALYCARE_REGISTRY_PERSON_KEYS_FILE')
d <- data.frame(subject=1:10,displayname=rep(c('Puls','SpO2'),each=5),meas_value='secret raw measurement')
out <- vital_inventory_from_data(d,'SP_VitaleVaerdier')
expect_equal(nrow(out$vital_descriptors),0L)
expect_true(all(out$vital_descriptor_assessment$inventory_status=='needs_person_key'))
mapping <- tempfile(fileext='.csv');write.csv(data.frame(table_name='SP_VitaleVaerdier',person_key='subject',reviewed=TRUE),mapping,row.names=FALSE)
Sys.setenv(DALYCARE_REGISTRY_PERSON_KEYS_FILE=mapping)
out <- vital_inventory_from_data(d,'SP_VitaleVaerdier')
expect_equal(sort(out$vital_descriptors$descriptor),c('Puls','SpO2'))
expect_true(all(out$vital_descriptor_assessment$inventory_status=='assessed_complete'))
expect_false(any(grepl('secret',unlist(out))))
d$displayname[1]<-'UNREVIEWED PRIVATE TOKEN'
out <- vital_inventory_from_data(d,'SP_VitaleVaerdier')
expect_equal(out$vital_descriptors$descriptor,'SpO2')
expect_true(all(out$vital_descriptor_assessment$inventory_status=='partial_withheld'))
expect_false(any(grepl('PRIVATE TOKEN',unlist(out))))
d<-data.frame(subject=1:21,displayname=c(rep('Puls',10),rep('Temp',10),'UNREVIEWED PRIVATE TOKEN'),meas_value='secret')
out<-vital_inventory_from_data(d,'SP_VitaleVaerdier')
expect_equal(sort(out$vital_descriptors$descriptor),c('Puls','Temp'))
expect_true(all(out$vital_descriptor_assessment$inventory_status=='partial_withheld'))
expect_false(any(grepl('PRIVATE|secret',unlist(out))))
Sys.unsetenv('DALYCARE_REGISTRY_PERSON_KEYS_FILE');unlink(mapping)
cat('PASS reviewed controlled vital inventory and unavailable key scope\n')
